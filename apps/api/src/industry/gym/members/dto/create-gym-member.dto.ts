import { IsEmail, IsNotEmpty, IsOptional, IsString } from "class-validator";

export class CreateGymMemberDto {
  @IsString()
  @IsNotEmpty()
  memberNo!: string;

  @IsString()
  @IsNotEmpty()
  firstName!: string;

  @IsString()
  @IsNotEmpty()
  lastName!: string;

  @IsOptional()
  @IsString()
  branchId?: string;

  @IsOptional()
  @IsEmail()
  email?: string;

  @IsOptional()
  @IsString()
  phone?: string;

  @IsOptional()
  @IsString()
  notes?: string;
}
